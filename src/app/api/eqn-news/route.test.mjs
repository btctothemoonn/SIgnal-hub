import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { NextRequest } from "next/server.js";
const dir = mkdtempSync(join(tmpdir(), "eqn-news-api-"));
process.env.EQN_NEWS_DB = join(dir, "news.sqlite");
process.env.EQN_NEWS_ENABLED = "false";
process.env.ADMIN_PASSWORD = "test-password";
process.env.ADMIN_SESSION_SECRET = "s".repeat(64);
process.env.SIGNAL_HUB_PUBLIC_ORIGIN = "https://hub.example";
const { proxy } = await import("../../../proxy.ts");
const { GET: feed } = await import("./route.ts");
const { GET: detail } = await import("./[id]/route.ts");
const { GET: market } = await import("./market/route.ts");
const { GET: stream } = await import("./stream/route.ts");
const { GET: sourcesGet, PUT: sourcesPut } = await import("./sources/route.ts");
const { createAdminSessionToken } = await import("../../../lib/admin-auth.ts");
const { getEqnNewsStore } = await import("../../../lib/eqn-news-store.ts");
const { normalizeEqnNews } = await import("../../../lib/eqn-news-core.ts");
try {
  for (const path of ["", "/stream", "/market", "/12", "/coin/BTC", "/channels", "/sources"]) assert.equal(proxy(new NextRequest(`https://hub.example/api/eqn-news${path}`)).status, 401);
  const res = await feed(new Request("https://hub.example/api/eqn-news?limit=bad"));
  assert.equal(res.status, 400);
  assert.equal((await feed(new Request("https://hub.example/api/eqn-news?before=bad"))).status, 400);
  assert.equal((await detail(new Request("https://hub.example/api/eqn-news/404"), { params: Promise.resolve({ id: "404" }) })).status, 404);
  assert.equal((await market(new Request("https://hub.example/api/eqn-news/market?venue=bad"))).status, 400);
  assert.equal((await market(new Request("https://hub.example/api/eqn-news/market?view=bad"))).status, 400);
  const item = normalizeEqnNews({ timestamp: 1794826821, news_title: "WS temporary", source_name: "BWENEWS", coins_included: [] }, "ws");
  getEqnNewsStore().upsert(item);
  assert.equal((await detail(new Request(`https://hub.example/api/eqn-news/${encodeURIComponent(item.id)}?venue=bad`), { params: Promise.resolve({ id: item.id }) })).status, 400);
  assert.equal((await detail(new Request(`https://hub.example/api/eqn-news/${encodeURIComponent(item.id)}?coin=BAD%2FCOIN`), { params: Promise.resolve({ id: item.id }) })).status, 400);
  const unknownDetail = await detail(new Request(`https://hub.example/api/eqn-news/${encodeURIComponent(item.id)}?coin=ETH&venue=hyperliquid`), { params: Promise.resolve({ id: item.id }) });
  assert.equal(unknownDetail.status, 200);
  const unknownBody = await unknownDetail.json();
  assert.ok(unknownBody.reactions.every((reaction) => reaction.change === null));
  assert.deepEqual(unknownBody.signals, []);
  const detailResponse = await detail(new Request(`https://hub.example/api/eqn-news/${encodeURIComponent(item.id)}`), { params: Promise.resolve({ id: item.id }) });
  assert.equal((await detailResponse.json()).item.id, item.id);
  const response = await feed(new Request("https://hub.example/api/eqn-news"));
  const body = await response.json();
  assert.equal(body.status.enabled, false);
  assert.equal(body.items[0].id, item.id);
  assert.match(response.headers.get("cache-control"), /no-store/);
  const abort = new AbortController();
  const eventResponse = await stream(new Request("https://hub.example/api/eqn-news/stream", { signal: abort.signal }));
  const reader = eventResponse.body.getReader();
  const event = new TextDecoder().decode((await reader.read()).value);
  assert.match(event, /event: message/);
  assert.match(event, /"type":"update"/);
  abort.abort();
  await reader.cancel();

  const cookie = `signal_hub_admin=${createAdminSessionToken()}`;
  const put = (body, init = {}) => sourcesPut(new Request("https://hub.example/api/eqn-news/sources", { method: "PUT", body: JSON.stringify(body), headers: { cookie, origin: "https://hub.example", "sec-fetch-site": "same-origin", ...init } }));
  assert.equal((await sourcesGet(new Request("https://hub.example/api/eqn-news/sources"))).status, 401);
  assert.equal((await sourcesPut(new Request("https://hub.example/api/eqn-news/sources", { method: "PUT", body: "{}" }))).status, 401);
  assert.equal((await put({ blocked: ["BWENEWS"] }, { origin: "https://evil.example" })).status, 403);
  assert.equal((await put({ blocked: ["BWENEWS"] }, { "sec-fetch-site": "cross-site" })).status, 403);
  assert.equal((await put({ blocked: "BWENEWS" })).status, 400);
  assert.equal((await put({ blocked: Array.from({ length: 201 }, (_, i) => `s${i}`) })).status, 400);
  const before = await (await sourcesGet(new Request("https://hub.example/api/eqn-news/sources", { headers: { cookie } }))).json();
  assert.deepEqual(before.sources.map((x) => [x.source, x.count, x.blocked]), [["BWENEWS", 1, false]]);
  const blockedResponse = await put({ blocked: ["bwenews", "Price Monitor", "BWENEWS"] });
  assert.equal(blockedResponse.status, 200);
  const blockedBody = await blockedResponse.json();
  assert.deepEqual(blockedBody.blocked, ["bwenews", "price monitor"], "case-insensitive, deduplicated keys");
  assert.deepEqual(blockedBody.sources.map((x) => [x.source, x.blocked]), [["BWENEWS", true], ["price monitor", true]], "blocked sources stay listed so they can be restored");
  assert.equal((await (await feed(new Request("https://hub.example/api/eqn-news"))).json()).items.length, 0, "existing blocked items are hidden");
  const monitor = normalizeEqnNews({ no: 77, time: "2026-11-17T00:00:00Z", zh: "价格监测", source: "Price Monitor", channels: ["pricechange"] }, "mcp");
  assert.ok(monitor, "fixture normalizes");
  assert.equal(getEqnNewsStore().upsert(monitor), false, "blocked sources are not ingested");
  assert.equal(getEqnNewsStore().get("77"), null);
  assert.equal((await put({ blocked: [] })).status, 200);
  assert.equal((await (await feed(new Request("https://hub.example/api/eqn-news"))).json()).items[0].id, item.id, "unblocking restores retained items");
  assert.equal(getEqnNewsStore().upsert(monitor), true);
  console.log("eqn-news route validation, proxy auth, WS lookup and generic SSE tests passed");
} finally { getEqnNewsStore().close(); rmSync(dir, { recursive: true, force: true }); }
