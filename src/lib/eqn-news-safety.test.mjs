import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { DatabaseSync } from "node:sqlite";
import { normalizeEqnNews, scoreEqnNews } from "./eqn-news-core.ts";
import { openEqnNewsStore } from "./eqn-news-store.ts";
import { createEqnClient, eqnFetchText, fillEqnChannelGap } from "./eqn-news-client.ts";
import { readEqnMarketContext, createEqnMarketClient } from "./eqn-news-market.ts";
import { collectEqnRelatedSignals } from "./eqn-news-related.ts";
const dir = mkdtempSync(join(tmpdir(), "eqn-news-safety-"));
const store = openEqnNewsStore(join(dir, "news.sqlite"));
try {
  const now = Date.now();
  const ws = normalizeEqnNews({ news_title: "English original", timestamp: Math.floor(now / 1000), source_name: "BWENEWS", coins_included: [] }, "ws", now);
  store.upsert(ws);
  store.upsert(normalizeEqnNews({ no: 99, time: new Date(Math.floor(now / 1000) * 1000 + 200).toISOString(), zh: "Translated title", en: "English original", source: "BWENEWS", coins: [] }, "mcp", now));
  assert.equal(store.feed({}).items.length, 1, "URL-less bilingual WS placeholder merges with official MCP");
  assert.equal(store.get(ws.id).id, "99");
  store.setState("status", { enabled: true, connected: true, updatedAt: now - 100000, lastMessageAt: now - 100000, error: null });
  assert.equal(store.status(now, true).connected, false);
  assert.match(store.status(now, true).error, /stale/);
  const record = (no) => ({ no, time: new Date(now).toISOString(), zh: "page", channels: ["main"], source: "test" });
  store.setState("watermark:main", { no: 1, time: now - 1000 });
  await assert.rejects(fillEqnChannelGap(store, { listNews: async () => ({ items: [record(9)], next_cursor: "stuck" }) }, "main", { maxPages: 3 }), /repeated/);
  assert.equal(store.getState("watermark:main").no, 1);
  let requests = 0;
  let clock = 1000;
  const client = createEqnClient({ now: () => clock, sleep: async (ms) => { clock += ms; }, store, fetch: async () => { requests++; return new Response(null, { status: 429, headers: { "retry-after": "3600" } }); } });
  await assert.rejects(client.listNews({ channel: "main" }), /rate limited/);
  assert.equal(requests, 1, "long Retry-After fails fast instead of hanging worker");
  assert.equal(store.getState("eqnBlockedUntil"), 3601000);
  await assert.rejects(eqnFetchText("https://example.test", {}, { fetch: async (_url, { signal }) => new Promise((_resolve, reject) => signal.addEventListener("abort", () => reject(new Error("abort")))), timeoutMs: 5 }), /timeout/);
  await assert.rejects(eqnFetchText("https://example.test", {}, { fetch: async () => new Response("123456789"), maxBytes: 3 }), /too large/);
  let detail = { title: "Listing XYZ", kind: "listing", source: "Binance EN", channels: ["major"], coins: [{ symbol: "XYZ", assetId: null, marketCapAtPublish: 100 }] };
  assert.equal(scoreEqnNews(detail), 100);
  assert.equal(scoreEqnNews({ ...detail, title: "ordinary", kind: "news", source: "unknown", channels: ["tradfi"], coins: [] }), 0);
  const alertsPath = join(dir, "alerts.sqlite");
  const signalsPath = join(dir, "signals.sqlite");
  const db = new DatabaseSync(alertsPath);
  db.exec("CREATE TABLE market_alert_tickers(symbol TEXT,market_cap_usd REAL,fdv_usd REAL,valuation_updated_at TEXT);CREATE TABLE market_alert_events(id TEXT,type TEXT,stage TEXT,symbol TEXT,occurred_at TEXT)");
  db.prepare("INSERT INTO market_alert_tickers VALUES(?,?,?,?)").run("BTCUSDT", 42, 84, new Date().toISOString());
  db.prepare("INSERT INTO market_alert_events VALUES(?,?,?,?,?)").run("a", "volatility", "up", "BTCUSDT", new Date(now).toISOString());
  db.close();
  const signals = new DatabaseSync(signalsPath);
  signals.exec("CREATE TABLE market_signals(id TEXT,kind TEXT,symbol TEXT,signal_at TEXT)");
  signals.prepare("INSERT INTO market_signals VALUES(?,?,?,?)").run("s", "pullback", "BTCUSDT", new Date(now).toISOString());
  signals.close();
  process.env.MARKET_SIGNALS_DB = signalsPath;
  const context = readEqnMarketContext("BTCUSDT", now - 1000, alertsPath);
  assert.equal(context.marketCap, 42);
  assert.equal(context.fdv, 84);
  assert.equal(context.signals.length, 2, "reads both existing alerts.sqlite and independent signals.sqlite stores");
  const related = collectEqnRelatedSignals(["BTC"], [{ text: "$BTC rising", createdAt: new Date(now).toISOString(), tweetUrl: "https://x.com/a/status/1" }, { text: "ABTC unrelated", createdAt: new Date(now).toISOString(), tweetUrl: "https://x.com/a/status/2" }, { text: "BTC old", createdAt: new Date(now - 2 * 86400000).toISOString(), messageUrl: "https://t.me/a/3" }], now);
  assert.equal(related.length, 1, "X/TG association uses exact token boundaries and 24h window");
  assert.equal(related[0].url, "https://x.com/a/status/1");
  let time = now; let failTicker = false; let failCandles = false;
  const market = createEqnMarketClient({ now: () => time, sleep: async (ms) => { time += ms; }, rateLimit: null, fetch: async (url) => {
    if (String(url).includes("exchangeInfo")) return Response.json({ symbols: [{ symbol: "BTCUSDT", baseAsset: "BTC", quoteAsset: "USDT", status: "TRADING", contractType: "PERPETUAL" }] });
    if (String(url).includes("24hr")) return failTicker ? new Response(null, { status: 503 }) : Response.json({ lastPrice: "100", priceChangePercent: "1", quoteVolume: "1000" });
    if (String(url).includes("klines")) return failCandles ? new Response(null, { status: 503 }) : Response.json([[now, 100, 102, 99, 101, 1]]);
    return Response.json({ lastFundingRate: ".01", openInterest: "4" });
  }, optionalWaitMs: 50 });
  await market.getMarket({ symbol: "BTC", venue: "binance", interval: "1m" });
  time += 20000; failTicker = true;
  const tickerDown = await market.getMarket({ symbol: "BTC", venue: "binance", interval: "1m" });
  assert.equal(tickerDown.price, 101, "a failed display ticker falls back to the freshly fetched live candle close");
  assert.equal(tickerDown.error, null);
  time += 20000; failCandles = true;
  const partial = await market.getMarket({ symbol: "BTC", venue: "binance", interval: "1m" });
  assert.equal(partial.price, 101);
  assert.match(partial.error, /Partial\/stale/);
  assert.equal(partial.candles[0].time, Math.floor(now / 1000), "stale fallback must not double-convert chart times");
  store.prune(now + 31 * 86400000);
  assert.equal(store.feed({}).items.length, 0);
  assert.equal(store.get(ws.id), null, "retention also removes id aliases");
  console.log("eqn-news safety, cooldown, timeouts, valuations, related events and stale market tests passed");
} finally { store.close(); rmSync(dir, { recursive: true, force: true }); }
