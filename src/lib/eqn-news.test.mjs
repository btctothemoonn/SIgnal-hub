import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const core = await import("./eqn-news-core.ts");
const { openEqnNewsStore } = await import("./eqn-news-store.ts");
const { createEqnClient, fillEqnChannelGap } = await import("./eqn-news-client.ts");
const { resolveEqnAsset, calculateEqnReactions, createEqnMarketClient } = await import("./eqn-news-market.ts");
const raw = (no, time = 1794826821689) => ({ no, time: new Date(time).toISOString(), channels: ["main"], source: "BWENEWS", zh: `Story ${no}`, en: `Original ${no}`, coins: ["BTC"], url: `https://eqn.news/main/${no}`, source_url: `https://example.com/${no}` });
const item = core.normalizeEqnNews(raw(15258), "mcp", 1794826822000);
assert.equal(item.publishedAt, 1794826821689);
assert.equal(item.title, "Story 15258");
assert.equal(item.coins[0].symbol, "BTC");
assert.equal(core.normalizeEqnNews({ news_title: "WS", source_name: "BWENEWS", timestamp: 1794826821, coins_included: [] }, "ws").publishedAt, 1794826821000);
assert.equal(core.normalizeEqnNews({ time: "broken", zh: "bad" }, "mcp"), null);
assert.equal(core.normalizeEqnNews({ news_title: "x".repeat(50000), timestamp: 1794826821 }, "ws").title.length, 16000);
assert.equal(core.normalizeEqnNews({ ...raw(1), images: ["/image/a.jpg", "javascript:bad"] }, "mcp").images[0], "https://eqn.news/image/a.jpg");

const dir = mkdtempSync(join(tmpdir(), "eqn-news-"));
let store;
try {
  store = openEqnNewsStore(join(dir, "news.sqlite"));
  const placeholder = core.normalizeEqnNews({ news_title: "WS", source_name: "BWENEWS", timestamp: 1794826821, url: "https://example.com/15258" }, "ws");
  store.upsert(placeholder);
  store.upsert(item);
  store.upsert(placeholder);
  assert.equal(store.feed({}).items.length, 1, "WS source URL + seconds merges with millisecond MCP record");
  assert.equal(store.get(placeholder.id).id, item.id, "old SSE/browser id remains resolvable");
  assert.equal(store.get(item.id).title, item.title, "late WS cannot downgrade MCP");
  store.upsert(core.normalizeEqnNews(raw(15259), "mcp"));
  const first = store.feed({ limit: 1 });
  assert.equal(first.items.length, 1);
  const second = store.feed({ limit: 1, before: first.nextCursor });
  assert.notEqual(first.items[0].id, second.items[0].id, "timestamp ties paginate stably");
  assert.equal(store.feed({ coin: "DOGE" }).items.length, 0);
  assert.equal(store.feed({ q: "%" }).items.length, 0, "LIKE wildcards are literal");
  assert.throws(() => store.feed({ before: "nonsense" }), /cursor/i);
  store.augment({ no: 15258, coins: [{ symbol: "BTC", asset_id: "bitcoin", mc_at_publish: 1000 }], data: { announcement_digest: { points: ["point"] } } });
  store.augment({ no: 15258, zh: "must not overwrite", coins: "drift", data: null });
  assert.equal(store.get(item.id).title, item.title);
  assert.deepEqual(store.get(item.id).digest, ["point"]);
  assert.equal(store.get(item.id).coins[0].marketCapAtPublish, 1000);

  store.setState("watermark:main", { no: 2, time: 1794826800000 });
  const calls = [];
  const pages = { latest: { items: [raw(5), raw(4)], next_cursor: "older" }, older: { items: [raw(3), raw(2, 1794826800000)], next_cursor: "oldest" } };
  const client = { listNews: async (args) => { calls.push(args); return pages[args.before ?? "latest"]; } };
  const partial = await fillEqnChannelGap(store, client, "main", { maxPages: 1 });
  assert.equal(partial.complete, false);
  assert.equal(store.getState("watermark:main").no, 2, "never advance persisted watermark before filling gap");
  await fillEqnChannelGap(store, client, "main", { maxPages: 3 });
  assert.equal(calls[0].before, undefined, "scan starts at newest, NOT old watermark");
  assert.equal(calls[1].before, "older");
  assert.equal(store.getState("watermark:main").no, 5);

  const messages = [];
  let now = 10000;
  let limited = true;
  const rpc = createEqnClient({ now: () => now, sleep: async (ms) => { now += ms; }, fetch: async (_url, opts) => {
    const request = JSON.parse(opts.body); messages.push({ request, headers: opts.headers });
    if (request.method === "initialize") return Response.json({ jsonrpc: "2.0", id: request.id, result: { protocolVersion: "2024-11-05", capabilities: {}, serverInfo: { name: "eqn" } } }, { headers: { "mcp-session-id": "session" } });
    if (!request.id) return new Response(null, { status: 202 });
    if (limited) { limited = false; return new Response(null, { status: 429, headers: { "retry-after": "2" } }); }
    return new Response(`event: message\ndata: ${JSON.stringify({ jsonrpc: "2.0", id: request.id, result: { content: [{ type: "text", text: JSON.stringify(pages.latest) }] } })}\n\n`, { headers: { "content-type": "text/event-stream" } });
  } });
  assert.equal((await rpc.listNews({ channel: "main", limit: 2 })).items.length, 2);
  assert.equal(messages[0].request.method, "initialize");
  assert.equal(messages[1].request.method, "notifications/initialized");
  assert.equal(messages.at(-1).headers["Mcp-Session-Id"], "session");
  assert.ok(now >= 12000, "429 respects global pause");
  assert.equal(messages.filter((x) => x.request.method === "tools/call").length, 2);
  assert.throws(() => core.parseEqnFeedQuery(new URLSearchParams("limit=nan")), /limit/);
  assert.equal(core.parseEqnFeedQuery(new URLSearchParams("limit=999")).limit, 200);
  assert.throws(() => core.parseEqnFeedQuery(new URLSearchParams("channel=invalid")), /channel/);

  const metadata = [{ symbol: "1000PEPEUSDT", baseAsset: "1000PEPE", quoteAsset: "USDT", status: "TRADING", contractType: "PERPETUAL" }, { symbol: "BTCUSDT", baseAsset: "BTC", quoteAsset: "USDT", status: "TRADING", contractType: "PERPETUAL" }];
  assert.equal(resolveEqnAsset("PEPE", "binance", metadata).pair, "1000PEPEUSDT");
  assert.equal(resolveEqnAsset("PEPE", "binance", metadata).multiplier, 1000);
  assert.equal(resolveEqnAsset("PEPE", "hyperliquid", [{ name: "kPEPE" }]).pair, "kPEPE");
  assert.equal(resolveEqnAsset("PEPE", "binance", metadata, "unrelated-token"), null);
  assert.equal(resolveEqnAsset("BT", "binance", metadata), null);
  const listing = { symbol: "NEWTOKENUSDT", baseAsset: "NEWTOKEN", quoteAsset: "USDT", status: "TRADING", contractType: "PERPETUAL" };
  assert.equal(resolveEqnAsset("NEWTOKEN", "binance", [listing]).pair, "NEWTOKENUSDT", "new listing exact exchange metadata is sufficient without aliasing");
  assert.equal(resolveEqnAsset("NEWTOKEN", "hyperliquid", [{ name: "NEWTOKEN" }]).pair, "NEWTOKEN");
  assert.equal(resolveEqnAsset("NEWTOKEN", "binance", [listing], "unknown-project"), null);
  assert.equal(resolveEqnAsset("NEWTOKEN", "binance", [listing, listing]), null, "ambiguous metadata fails closed");
  assert.equal(resolveEqnAsset("PEPE", "binance", [{ ...metadata[0], status: "BREAK" }]), null);
  const candles = [0, 60000, 120000, 180000].map((time, i) => ({ time, open: 100 + i * 10, close: 109 + i * 10, high: 120 + i * 10, low: 90 + i * 10, volume: 1 }));
  const reaction = calculateEqnReactions(30000, candles, 190000, [1, 5]);
  assert.equal(reaction[0].change, (120 / 110 - 1) * 100, "uses first candle open at/after publication and target, not pre-publication OHLC");
  assert.equal(reaction[1].change, null, "future target remains pending");
  assert.equal(calculateEqnReactions(30000, [candles[0]], 999999, [1])[0].change, null);
  let marketRequests = 0;
  const market = createEqnMarketClient({ fetch: async (url, opts) => {
    marketRequests++;
    if (String(url).includes("exchangeInfo")) return Response.json({ symbols: metadata });
    if (String(url).includes("klines")) return Response.json([[1794826800000, "100", "120", "90", "110", "4"]]);
    if (String(url).includes("24hr")) return Response.json({ lastPrice: "110", priceChangePercent: "10", quoteVolume: "1000" });
    if (String(url).includes("premiumIndex")) return Response.json({ lastFundingRate: "0.0001" });
    if (String(url).includes("openInterest")) return Response.json({ openInterest: "12" });
    const body = JSON.parse(opts.body);
    if (body.type === "metaAndAssetCtxs") return Response.json([{ universe: [{ name: "BTC" }, { name: "kPEPE" }] }, [{ markPx: "110", prevDayPx: "100", dayNtlVlm: "1000", funding: "0.0001", openInterest: "12" }, { markPx: "0.011", prevDayPx: "0.01", dayNtlVlm: "1000", funding: "0.0001", openInterest: "12" }]]);
    if (body.type === "candleSnapshot") return Response.json([{ t: 1794826800000, o: "100", h: "120", l: "90", c: "110", v: "4" }]);
    throw new Error(`unexpected ${url}`);
  }, valuations: () => ({ marketCap: 42, fdv: 84 }), rateLimit: null });
  const binance = await market.getMarket({ symbol: "BTC", venue: "binance", interval: "1m" });
  assert.equal(binance.pair, "BTCUSDT");
  assert.equal(binance.marketCap, 42);
  assert.equal(binance.candles[0].close, 110);
  assert.equal(binance.candles[0].time, 1794826800, "public NewsMarket candle time is UNIX seconds");
  assert.deepEqual(Object.keys(binance).sort(), ["symbol", "pair", "venue", "price", "change24h", "marketCap", "fdv", "volume24h", "fundingRate", "openInterest", "candles", "fetchedAt", "error"].sort());
  const scaled = await market.getMarket({ symbol: "PEPE", venue: "binance", interval: "1m" });
  assert.equal(scaled.symbol, "PEPE");
  assert.equal(scaled.pair, "1000PEPEUSDT");
  assert.equal(scaled.price, 110, "UI limit prices use the native scaled contract price, not per-token prices");
  assert.equal(scaled.candles[0].open, 100);
  assert.equal(scaled.candles[0].volume, 4, "native instrument quantity");
  assert.equal(scaled.openInterest, 1320, "native contract quantity multiplied by native price exactly once");
  assert.equal((await market.getCandles({ symbol: "PEPE", venue: "binance", interval: "1m" }))[0].time, 1794826800000, "internal candle API stays milliseconds");
  const count = marketRequests;
  await market.getMarket({ symbol: "BTC", venue: "binance", interval: "1m" });
  assert.equal(marketRequests, count, "market data is cached");
  const hl = await market.getMarket({ symbol: "BTC", venue: "hyperliquid", interval: "1m" });
  assert.equal(hl.pair, "BTC");
  assert.equal(hl.change24h, 10.000000000000009);
  assert.equal(hl.candles[0].open, 100);
  const hlScaled = await market.getMarket({ symbol: "PEPE", venue: "hyperliquid", interval: "1m" });
  assert.equal(hlScaled.pair, "kPEPE");
  assert.equal(hlScaled.price, 0.011, "Hyperliquid scaled instrument price is native too");
  assert.equal(hlScaled.openInterest, 12 * 0.011);
  assert.equal(hlScaled.candles[0].open, 100);
  assert.equal((await market.getMarket({ symbol: "BT", venue: "binance", interval: "1m" })).pair, null);
  console.log("eqn-news protocol, store, gap fill, mapping, reaction and market tests passed");
} finally {
  store?.close();
  rmSync(dir, { recursive: true, force: true });
}
