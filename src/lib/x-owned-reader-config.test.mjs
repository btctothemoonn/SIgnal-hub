import assert from "node:assert/strict";
import { getXOwnedReaderConfig, ownedReaderStaleAfterMs, selectXOwnedReaderAccounts, X_OWNED_STALE_FLOOR_MS, X_OWNED_STALE_SLACK_MS, xOwnedReaderSoftCooldownMs } from "./x-owned-reader-config.ts";

const disabled = getXOwnedReaderConfig({});
assert.equal(disabled.enabled, false);
assert.deepEqual(selectXOwnedReaderAccounts(["Hzzzz666", "PHOTONCAP", "Established985", "newAuthor"], disabled), ["Hzzzz666", "PHOTONCAP"]);
const enabled = getXOwnedReaderConfig({ X_OWNED_READER_ENABLED: "true", X_OWNED_READER_USERNAMES: "@PhotonCap,newAuthor", X_OWNED_READER_MAX_REQUESTS: "900", X_OWNED_READER_DEADLINE_MS: "999999", X_OWNED_READER_MIN_INTERVAL_MS: "1", X_OWNED_READER_MAX_PAGES: "90", X_OWNED_READER_INTERVAL_MS: "1" });
assert.equal(enabled.enabled, true);
assert.deepEqual(selectXOwnedReaderAccounts(["PHOTONCAP", "newAuthor", "Hzzzz666", "Other"], enabled), ["PHOTONCAP", "newAuthor"]);
assert.equal(enabled.maxRequests, 80);
assert.equal(enabled.deadlineMs, 180000);
assert.equal(enabled.minIntervalMs, 2000);
assert.equal(enabled.maxPages, 5);
assert.equal(enabled.intervalMs, 300000);
assert.equal(enabled.staleAfterMs, ownedReaderStaleAfterMs(enabled.intervalMs));
assert.equal(enabled.staleAfterMs, Math.max(X_OWNED_STALE_FLOOR_MS, enabled.intervalMs + X_OWNED_STALE_SLACK_MS));
assert.equal(enabled.softCooldownEnabled, true);
assert.equal(enabled.structuralIsolateAfter, 5);
assert.equal(enabled.structuralRetryMs, 6 * 60 * 60_000);
assert.equal(xOwnedReaderSoftCooldownMs(enabled), enabled.intervalMs);
const tenMinutes = getXOwnedReaderConfig({ X_OWNED_READER_INTERVAL_MS: "600000" });
assert.equal(tenMinutes.intervalMs, 600000);
assert.ok(tenMinutes.staleAfterMs >= 22 * 60_000, "10 minute interval keeps stale behind the cooldown window");
assert.equal(tenMinutes.staleAfterMs, Math.max(X_OWNED_STALE_FLOOR_MS, 600000 + X_OWNED_STALE_SLACK_MS));
assert.equal(getXOwnedReaderConfig({ X_OWNED_READER_INTERVAL_MS: "600000", X_OWNED_READER_STALE_AFTER_MS: "600000" }).staleAfterMs, 600000);
assert.equal(getXOwnedReaderConfig({ X_OWNED_READER_INTERVAL_MS: "600000", X_OWNED_READER_STALE_AFTER_MS: "0" }).staleAfterMs, tenMinutes.staleAfterMs);
assert.equal(getXOwnedReaderConfig({ X_OWNED_READER_SOFT_COOLDOWN: "false" }).softCooldownEnabled, false);
assert.equal(xOwnedReaderSoftCooldownMs(getXOwnedReaderConfig({ X_OWNED_READER_SOFT_COOLDOWN: "false" })), null);
assert.equal(xOwnedReaderSoftCooldownMs(getXOwnedReaderConfig({ X_OWNED_READER_INTERVAL_MS: "900000" })), null);
assert.equal(getXOwnedReaderConfig({ X_OWNED_READER_STRUCTURAL_ISOLATE_AFTER: "9", X_OWNED_READER_STRUCTURAL_RETRY_MS: "1000" }).structuralIsolateAfter, 9);
assert.deepEqual(selectXOwnedReaderAccounts(["hzzzz666", "Hzzzz666", "bad-name", "truth:Someone"], disabled), ["hzzzz666"]);
console.log("Owned config: disabled default, explicit allowlist, configured intersection, stale formula and hard budget bounds passed.");
